drop database if exists dblari;
create database dblari;
use dblari;
 
-- Tabela de Clientes (Agora é a tabela principal)
create table tbclientes(
    idCli int not null auto_increment,
    nomecli varchar(100) not null,
    telcel char(11) not null unique, -- Telefone único para identificar o cliente
    primary key(idCli)
);
 
-- Tabela de Agendamentos
create table tbagendamentos(
    idAgend int auto_increment not null,
    data_agend date not null,
    horario_agend time not null,
    idCli int not null,
    servico varchar(100) not null,
    primary key(idAgend),
    foreign key(idCli) references tbclientes(idCli)
);
 
-- Tabela de Serviços oferecidos pela clínica
create table tbservicos(
    idServico int not null auto_increment,
    nome_Servico varchar(100) not null,
    descricao varchar(255),
    preco decimal(9,2),
    duracao time, 
    primary key(idServico)
);
 
-- Horários disponíveis para marcação
create table tbdisponibilidade(
    idDisp int not null auto_increment,
    data_disp date not null,
    horario_disp time not null,
    status enum('disponivel', 'reservado') default 'disponivel',
    primary key(idDisp)
);

